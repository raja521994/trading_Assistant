"""Signal state machine: WATCH -> SETUP -> TRIGGERED -> EXITED, with INVALIDATED / EXPIRED terminals."""

from __future__ import annotations

import time
from typing import TYPE_CHECKING, Any

from sqlalchemy import select
from sqlalchemy.orm import Session

from ..models import Signal, SignalEvent

if TYPE_CHECKING:
    from ..backtest.engine import Trade
    from ..quant.strategies.base import Strategy

WATCH, SETUP, TRIGGERED, INVALIDATED, EXITED, EXPIRED = (
    "WATCH", "SETUP", "TRIGGERED", "INVALIDATED", "EXITED", "EXPIRED")
STATES = [WATCH, SETUP, TRIGGERED, INVALIDATED, EXITED, EXPIRED]
TERMINAL = {INVALIDATED, EXITED, EXPIRED}
ACTIVE = {WATCH, SETUP, TRIGGERED}
ALLOWED: dict[str, set[str]] = {
    WATCH: {SETUP, TRIGGERED, INVALIDATED, EXPIRED},
    SETUP: {TRIGGERED, INVALIDATED, EXPIRED},
    TRIGGERED: {EXITED},
    INVALIDATED: set(),
    EXITED: set(),
    EXPIRED: set(),
}
DESCRIPTIONS = {
    WATCH: "Conditions partially met; monitoring. Not actionable.",
    SETUP: "All entry conditions met on the latest completed bar; entry reference is the next bar's open.",
    TRIGGERED: "Entry reference has traded; setup is live until stop, target, strategy exit or time limit.",
    INVALIDATED: "Stop / invalidation level hit before entry triggered.",
    EXITED: "Triggered setup closed by stop, target, strategy exit or time limit (outcome recorded).",
    EXPIRED: "Setup or watch condition lapsed without triggering.",
}


class InvalidTransition(ValueError):
    pass


def can_transition(src: str, dst: str) -> bool:
    return dst in ALLOWED.get(src, set())


def transition(session: Session, sig: Signal, dst: str, reason: str, price: float | None = None,
               ts: int | None = None) -> None:
    if sig.state == dst:
        return
    if not can_transition(sig.state, dst):
        raise InvalidTransition(f"{sig.state} -> {dst} not allowed")
    now = ts or int(time.time())
    session.add(SignalEvent(signal_id=sig.id, ts=now, from_state=sig.state, to_state=dst, price=price, reason=reason))
    sig.state = dst
    sig.updated_at = now


def create_signal(session: Session, uid: str, rec: dict[str, Any], origin: str = "live_scan") -> Signal:
    now = int(time.time())
    sig = Signal(uid=uid, provider=rec.get("provider", "sample"), origin=origin, symbol=rec["symbol"], exchange=rec["exchange"], mode=rec["mode"],
                 strategy=rec["strategy"], direction=rec["direction_code"], action=rec["action"], state=rec["state"],
                 score=rec["score"], generated_at=now, data_ts=rec["data_ts_epoch"], expires_at=rec["expires_at_epoch"],
                 updated_at=now, payload=rec, outcome=None)
    session.add(sig)
    session.flush()
    session.add(SignalEvent(signal_id=sig.id, ts=now, from_state=None, to_state=rec["state"],
                            price=rec.get("reference_price"), reason=f"Created by {origin.replace('_', ' ')}"))
    return sig


def record_replay_signal(session: Session, strategy: "Strategy", t: "Trade", provider: str = "sample") -> int:
    if t.exit_reason == "End of test period":
        return 0  # still open at the end of data; live scanner tracks it
    uid = f"replay:{provider}:{strategy.meta.id}:{t.exchange}:{t.symbol}:{t.entry_ts}"
    if session.scalar(select(Signal.id).where(Signal.uid == uid)) is not None:
        return 0
    from datetime import datetime

    entry_epoch = int(datetime.fromisoformat(t.entry_ts).timestamp())
    exit_epoch = int(datetime.fromisoformat(t.exit_ts).timestamp())
    result = "target" if t.exit_reason.startswith("Target") else (
        "stop" if t.exit_reason.startswith("Stop") else "strategy/time exit")
    payload = {
        "symbol": t.symbol, "exchange": t.exchange, "strategy": strategy.meta.id, "strategy_name": strategy.meta.name,
        "strategy_version": strategy.meta.version, "mode": strategy.meta.modes[0], "direction_code": t.direction,
        "direction": "bullish" if t.direction == "LONG" else "bearish", "action": "BUY" if t.direction == "LONG" else "SELL",
        "state": EXITED, "reference_price": t.entry_price, "stop_loss": t.stop,
        "targets": [t.target] if t.target is not None else [], "supporting_evidence": t.signal_reasons,
        "origin_note": "Historical replay: generated by running the strategy over recent stored bars "
                       "(fills at next open, same rules as the backtester).",
    }
    sig = Signal(uid=uid, provider=provider, origin="historical_replay", symbol=t.symbol, exchange=t.exchange,
                 mode=strategy.meta.modes[0], strategy=strategy.meta.id, direction=t.direction, action=payload["action"],
                 state=EXITED, score=0.0, generated_at=entry_epoch, data_ts=entry_epoch, expires_at=exit_epoch,
                 updated_at=exit_epoch, payload=payload,
                 outcome={"result": result, "exit_reason": t.exit_reason, "entry_price": t.entry_price,
                          "exit_price": t.exit_price, "r_multiple": t.r_multiple, "net_pnl": t.net_pnl, "qty": t.qty,
                          "return_pct": t.return_pct, "entry_ts": t.entry_ts, "exit_ts": t.exit_ts,
                          "bars_held": t.bars_held})
    session.add(sig)
    session.flush()
    session.add(SignalEvent(signal_id=sig.id, ts=entry_epoch, from_state=None, to_state=TRIGGERED,
                            price=t.entry_price, reason="Replay: entry at next open"))
    session.add(SignalEvent(signal_id=sig.id, ts=exit_epoch, from_state=TRIGGERED, to_state=EXITED,
                            price=t.exit_price, reason=f"Replay: {t.exit_reason}"))
    return 1
